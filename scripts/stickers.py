"""The chat stickers for Mini: the phone's still stickers (Android assets/stickers, animated ones left out — Mini
shows those by their code) cut to 96 px high PNGs with a small palette.

    python -I scripts/stickers.py <android>/app/src/main/assets/stickers
    # writes assets/stickers/*.png, apps/mini/ui/stickers.slint and crates/social/src/stickers_mini.txt
"""
import json
import pathlib
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEIGHT = 96


def main() -> None:
    src = pathlib.Path(sys.argv[1])
    spec = json.loads((src / "stickers.json").read_text(encoding="utf-8"))["stickers"]
    out = ROOT / "assets" / "stickers"
    out.mkdir(parents=True, exist_ok=True)
    still = [s for s in spec if not s.get("anim")]
    lines = [
        "// Generated by scripts/stickers.py: the phone's still chat stickers, in the order of stickers_mini.txt.",
        "export global Stickers {",
        "    out property <[image]> all: [",
    ]
    ratios = []
    for s in still:
        img = Image.open(src / f"{s['id']}.webp").convert("RGBA")
        if img.height > HEIGHT:
            img = img.resize((max(1, round(img.width * HEIGHT / img.height)), HEIGHT), Image.LANCZOS)
        img.quantize(colors=128, method=Image.Quantize.FASTOCTREE).save(out / f"{s['id']}.png", optimize=True)
        lines.append(f'        @image-url("../../../assets/stickers/{s["id"]}.png"),')
        ratios.append(f"{s['id']} {img.width / img.height:.3f}")
    lines += ["    ];", "}", ""]
    (ROOT / "apps" / "mini" / "ui" / "stickers.slint").write_bytes("\n".join(lines).encode("utf-8"))
    # id and width/height, one per line, in the same order (the index is the picture in Stickers.all).
    (ROOT / "crates" / "social" / "src" / "stickers_mini.txt").write_bytes("\n".join(ratios).encode("utf-8"))
    total = sum(p.stat().st_size for p in out.glob("*.png"))
    print(len(still), "stickers,", total // 1024, "KB")


if __name__ == "__main__":
    main()
