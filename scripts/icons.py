"""Writes apps/mini/ui/icons.slint: the Mini icons as vector paths taken from the tabler icon font.

Why paths and not the font: the subset tabler font has its glyphs pushed to the left edge of the advance (no side
bearings), so centred text puts every icon a few pixels left and the font's ascent/descent moves it vertically.
Here each outline is moved so the centre of its ink box sits at the centre of a 1000×1000 box (1000 units = the
24-unit tabler design grid = one em). Icons with a heavy side (the play triangle) are moved half-way toward their
area centroid, which looks centred to the eye.

Usage: python -I scripts/icons.py [full tabler-icons.ttf]  (the full font from pc/ has every icon; the subset in
assets/ only those the pc UI used)
"""
import pathlib
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.statisticsPen import StatisticsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "assets" / "fonts" / "tabler-icons.ttf"
OUT = ROOT / "apps" / "mini" / "ui" / "icons.slint"

# Mini name -> tabler code point (names of assets/icons.json in brackets).
ICONS = {
    "home": 0xEAC1,  # home
    "search": 0xEB1C,  # search
    "link": 0xEADE,  # link
    "users": 0xEBF2,  # users
    "puzzle": 0xEB10,  # puzzle
    "download": 0xEA96,  # download
    "upload": 0xEA9D,  # upload
    "chevron-left": 0xEA60,
    "chevron-right": 0xEA61,
    "plus": 0xEB0B,
    "x": 0xEB55,
    "heart": 0xEABE,
    "heart-filled": 0xF67C,
    "play": 0xF691,  # playerPlayFilled
    "pause": 0xF690,  # playerPauseFilled
    "next": 0xF694,  # playerSkipForwardFilled
    "prev": 0xF693,  # playerSkipBackFilled
    "shuffle": 0xF000,  # arrowsShuffle
    "repeat": 0xEB72,
    "volume": 0xEB51,
    "list": 0xEB6B,  # playlist
    "sort": 0xEB5A,  # arrowsSort
    "layout-right": 0xF006,
    "moon": 0xEAF8,
    "music": 0xEAFC,
    "settings": 0xEB20,
    "check": 0xEA5E,
    "sun": 0xEB30,
}
OPTICAL = {"play"}


def main():
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    lines = [
        "// Generated by scripts/icons.py from the tabler icon font. Do not edit.",
        "// Each icon is an SVG path in a 1000x1000 box with its ink centred (see the script for why).",
        "",
        "export global Icons {",
    ]
    for name, cp in ICONS.items():
        glyph = glyphs[cmap[cp]]
        bp = BoundsPen(glyphs)
        glyph.draw(bp)
        x0, y0, x1, y1 = bp.bounds
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        if name in OPTICAL:
            sp = StatisticsPen(glyphs)
            glyph.draw(sp)
            cx = (cx + sp.meanX) / 2
        sp = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
        # Font y goes up, path y goes down: flip and move the ink centre to (500, 500).
        glyph.draw(TransformPen(sp, (1, 0, 0, -1, 500 - cx, 500 + cy)))
        lines.append(f'    out property <string> {name}: "{sp.getCommands()}";')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(ICONS)} icons, {OUT.stat().st_size // 1024} KB")


main()
