"""Color pictures of the chat reactions (Android ChatReactions.EMOJI, the same order): Slint's software renderer
draws emoji fonts in one color, so Mini shows these instead. Twemoji 15.1 (CC-BY 4.0), cut to 40 px.

    python scripts/emoji.py   # writes assets/emoji/*.png and apps/mini/ui/emoji.slint
"""
import io
import pathlib
import urllib.request

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
EMOJI = ["❤️", "👍", "🔥", "😂", "😭", "😍", "🤯", "👎", "😢", "😮", "😡", "🤔", "👏", "🎉", "💯", "🙏", "👀", "😎", "🤣",
         "😁", "🤗", "🤝", "💔", "😱", "🤮", "🤡", "💩", "💀", "🙈", "😴", "😈", "🤬", "🌚", "⚡", "🏆", "🎵", "🎧", "🍓",
         "✅", "🙄"]
BASE = "https://cdn.jsdelivr.net/gh/jdecked/twemoji@15.1.0/assets/72x72/"


def code(e: str) -> str:
    # Twemoji names drop the variation selector.
    return "-".join(f"{ord(c):x}" for c in e if c != "️")


def main() -> None:
    out = ROOT / "assets" / "emoji"
    out.mkdir(parents=True, exist_ok=True)
    for e in EMOJI:
        f = out / f"{code(e)}.png"
        if f.exists():
            continue
        raw = urllib.request.urlopen(BASE + code(e) + ".png", timeout=30).read()
        img = Image.open(io.BytesIO(raw)).convert("RGBA").resize((40, 40), Image.LANCZOS)
        img.quantize(colors=64, method=Image.Quantize.FASTOCTREE).save(f, optimize=True)
    lines = [
        "// Generated by scripts/emoji.py: the chat reactions as color pictures, in Android's order.",
        "export global Emoji {",
        "    out property <[image]> all: [",
    ]
    lines += [f'        @image-url("../../../assets/emoji/{code(e)}.png"), // {e}' for e in EMOJI]
    lines += ["    ];", "    // The reaction keys of the same pictures."]
    lines += ["    out property <[string]> keys: ["] + [f'        "e:{e}",' for e in EMOJI] + ["    ];", "}", ""]
    (ROOT / "apps" / "mini" / "ui" / "emoji.slint").write_bytes("\n".join(lines).encode("utf-8"))
    (ROOT / "crates" / "social" / "src" / "emoji.txt").write_bytes("\n".join(EMOJI).encode("utf-8"))
    print(len(EMOJI), sum(p.stat().st_size for p in out.glob("*.png")))


if __name__ == "__main__":
    main()
